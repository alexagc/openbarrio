def generate_sample_facilities_csv(output_path: str, facilities: list[dict] = None) -> str:
    """Exports sample civic facilities to a standardized CSV file."""
    if facilities is None:
        facilities = SAMPLE_CIVIC_FACILITIES

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    fieldnames = ["id", "type", "subtype", "name", "latitude", "longitude", "municipality_code", "postal_code"]

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(facilities)

    print(f"Sample civic facilities CSV exported to: {output_path} ({len(facilities)} facilities).")
    return output_path


def generate_sample_facilities_json(output_path: str, facilities: list[dict] = None) -> str:
    """Exports sample civic facilities to a standardized JSON file."""
    if facilities is None:
        facilities = SAMPLE_CIVIC_FACILITIES

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(facilities, f, indent=2, ensure_ascii=False)

    print(f"Sample civic facilities JSON exported to: {output_path} ({len(facilities)} facilities).")
    return output_path


