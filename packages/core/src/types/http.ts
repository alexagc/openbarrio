import { Type, Static } from '@sinclair/typebox';

export const ProblemDetailsSchema = Type.Object({
  type: Type.String({ format: 'uri', description: 'URI reference identifying the problem type' }),
  title: Type.String({ description: 'Short, human-readable summary of the problem type' }),
  status: Type.Number({ description: 'HTTP status code generated by the origin server' }),
  detail: Type.String({ description: 'Human-readable explanation specific to this occurrence of the problem' }),
  instance: Type.Optional(Type.String({ description: 'URI reference identifying the specific occurrence of the problem' })),
  invalidParams: Type.Optional(Type.Array(Type.Object({
    name: Type.String(),
    reason: Type.String(),
  }), { description: 'Specific invalid parameters when status is 400' })),
});

export const AuditCoordsQuerySchema = Type.Object({
  lat: Type.Number({ minimum: -90, maximum: 90, description: 'Latitude coordinate (WGS84 EPSG:4326)' }),
  lon: Type.Number({ minimum: -180, maximum: 180, description: 'Longitude coordinate (WGS84 EPSG:4326)' }),
});

export const AuditRefcatParamsSchema = Type.Object({
  refcat: Type.String({
    pattern: '^[0-9A-Za-z]{14,20}$',
    description: 'Spanish Cadastral Reference (14 digits parcel or 20 digits property code)',
  }),
});

export type ProblemDetails = Static<typeof ProblemDetailsSchema>;
export type AuditCoordsQuery = Static<typeof AuditCoordsQuerySchema>;
export type AuditRefcatParams = Static<typeof AuditRefcatParamsSchema>;
